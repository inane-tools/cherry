import { readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const iconStylesPath = join(project, 'src/lib/ui/icons.css');
const weights = ['regular', 'fill', 'duotone'];

async function iconNames(directory, names = new Set()) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await iconNames(path, names);
    else if (/\.(svelte|ts|css)$/.test(entry.name) && path !== iconStylesPath) {
      const source = await readFile(path, 'utf8');
      for (const [name] of source.matchAll(/\bph-[a-z][a-z0-9-]*\b/g)) {
        if (!weights.some(weight => name === 'ph-' + weight)) names.add(name);
      }
    }
  }
  return [...names].sort();
}

/** Keep only used icon selectors and WOFF2 assets from the official package. */
export async function generateIconStyles() {
  const names = await iconNames(join(project, 'src'));
  const output = ['/* Generated by npm run icons:generate. Phosphor Icons, MIT: https://github.com/phosphor-icons/web */'];
  for (const weight of weights) {
    const source = await readFile(join(project, 'node_modules/@phosphor-icons/web/src', weight, 'style.css'), 'utf8');
    const blocks = [...source.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selector, body]) => ({ selector: selector.trim(), body }));
    const selector = weight === 'regular' ? '.ph' : '.ph-' + weight;
    const base = blocks.find(block => block.selector === selector);
    const family = /font-family:\s*"([^"]+)"/.exec(base?.body ?? '')?.[1];
    if (!family) throw Error('Missing Phosphor weight: ' + weight);
    output.push(`@font-face { font-family: "${family}"; src: url("@phosphor-icons/web/${weight}/${family}.woff2") format("woff2"); font-weight: normal; font-style: normal; font-display: block; }`);
    output.push(`${selector} {${base.body}}`);
    for (const name of names) {
      const before = blocks.find(block => block.selector === `${selector}.${name}:before`);
      const after = blocks.find(block => block.selector === `${selector}.${name}:after`);
      if (!before || (weight === 'duotone' && !after)) throw Error(`Unknown Phosphor icon: ${name} (${weight})`);
      output.push(`${before.selector} {${before.body}}`);
      if (after) output.push(`${after.selector} {${after.body}}`);
    }
  }
  output.push('.ph, .ph-fill, .ph-duotone { display: inline-block; flex-shrink: 0; }');
  return output.join('\n') + '\n';
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const css = await generateIconStyles();
  const previous = await readFile(iconStylesPath, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
  if (previous !== css) await writeFile(iconStylesPath, css);
  console.log('Phosphor styles ready (regular, fill, duotone; WOFF2 only).');
}
